def _slack_request_valid(request):
    """Authenticate the unchanged request bytes and reject replay windows."""
    secret = getattr(settings, 'SLACK_SIGNING_SECRET', '')
    timestamp = request.headers.get('X-Slack-Request-Timestamp', '')
    signature = request.headers.get('X-Slack-Signature', '')
    if (not secret or not re.fullmatch(r'[0-9]{1,20}', timestamp)
            or not re.fullmatch(r'v0=[0-9a-f]{64}', signature)):
        return False
    try:
        if abs(time.time() - int(timestamp)) > 300:
            return False
    except (TypeError, ValueError):
        return False
    signed = b'v0:' + timestamp.encode('ascii') + b':' + request.body
    expected = 'v0=' + hmac.new(secret.encode(), signed, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, signature)


def _slack_document_reply(org, event_data, question):
    """Only disclose document answers to a mapped user in a one-person DM."""
    origin = getattr(settings, 'DOCUMENT_EXPLORER_PUBLIC_URL', '').rstrip('/')
    parsed_origin = urlsplit(origin)
    if parsed_origin.scheme not in ('https', 'http') or not parsed_origin.netloc:
        origin = ''
    location = f' Open <{origin}/knowledge|Document Explorer> in DataGov.' if origin else ' Open Document Explorer in DataGov.'
    if event_data.get('channel_type') != 'im' or not str(event_data.get('channel', '')).startswith('D'):
        return 'Document answers are available in a direct message with a verified DataGov account.' + location
    person = DataPerson.objects.filter(
        organization=org, slack_user_id=event_data.get('user', ''),
        user__is_active=True,
    ).exclude(slack_user_id='').select_related('user').first()
    if not person or not OrganizationMembership.objects.filter(
        organization=org, user=person.user,
    ).exists():
        return 'Ask your DataGov administrator to link your Slack member ID to your account.' + location
    if not question:
        return 'Use `documents: your question` to search documents you can access.' + location
    from knowledge.chat import answer_document_question
    from knowledge.permissions import filter_citations
    result = answer_document_question(org, person.user, question)
    citations = result.get('citations', [])
    allowed = filter_citations(org, person.user, citations)
    if len(allowed) != len(citations):
        return 'Source access changed while preparing this answer. Please try again in DataGov.' + location
    # Citation URLs are generated by DataGov. Never relay URLs supplied in PDF
    # text, by the retrieval model, or by the external source.
    links = []
    for citation in allowed:
        path = citation.get('datagov_url') or ''
        if path.startswith('/knowledge/documents/') and not path.startswith('//') and origin:
            links.append(f'<{origin}{path}|Open source in DataGov>')
    return result['answer'] + ('\n\n' + '\n'.join(dict.fromkeys(links)) if links else '')

def run_slack_event_sync(event_data, bot_token):
    """
    Module-level function required by Django Q to run background tasks.
    Runs synchronously using WebClient instead of AsyncWebClient.

    Returns the assistant's reply text so Django-Q stores it on
    ``Task.result`` — that is what surfaces in Org Settings → Queues, so an
    admin can read what the bot actually answered (or why it failed). On error
    we log the traceback and return an error string rather than re-raising, so
    Django-Q does not retry and post a duplicate reply into the Slack thread.
    """
    try:
        return process_slack_event(event_data, bot_token)
    except Exception as e:
        import traceback
        traceback.print_exception(type(e), e, e.__traceback__, file=sys.stderr)
        # Name the exception CLASS, not just its message: the failures that
        # actually happen here — httpx.ReadTimeout / ConnectTimeout /
        # RemoteProtocolError, asyncio.CancelledError, TimeoutError — all carry
        # an EMPTY str(), which rendered in the Queues panel as a bare
        # "⚠️ Slack reply failed:" with nothing after the colon and no way to
        # tell a network timeout from an application bug.
        detail = str(e).strip() or '(no message — typically a network timeout)'
        message = f"⚠️ Slack reply failed: {type(e).__name__}: {detail}"
        _post_failure_to_thread(event_data, bot_token, message)
        return message


def _post_failure_to_thread(event_data, bot_token, message):
    """Best-effort: tell the Slack thread that the turn failed.

    Without this the only trace of a failure is ``Task.result`` in the Queues
    panel — the person who asked in Slack just sees silence and re-asks. Never
    raises: a failure to report a failure must not mask the original error.
    """
    try:
        WebClient(token=bot_token).chat_postMessage(
            channel=event_data.get('channel'),
            thread_ts=event_data.get('thread_ts') or event_data.get('ts'),
            text=message,
        )
    except Exception:
        import traceback
        traceback.print_exc(file=sys.stderr)

def process_slack_event(event_data, bot_token):
    # Every queued event carries the verified installation identity. Old tasks
    # without it fail closed rather than choosing a token's first tenant.
    team_id = event_data.get('_slack_team_id')
    org = Organization.objects.filter(slack_team_id=team_id, slack_bot_token=bot_token).first() if team_id else None
    if org is None:
        return 'Slack installation is not mapped to a DataGov organization.'
    client = WebClient(token=bot_token)
    channel_id = event_data.get('channel')
    # By passing the original event's ts as thread_ts, we ensure the bot ALWAYS replies in a thread.
    # If the user already messaged in a thread, thread_ts will be set and we keep appending.
    # If they just mentioned in the main channel, thread_ts will be their message's ts, so the bot creates a thread.
    thread_ts = event_data.get('thread_ts') or event_data.get('ts')

    # Get bot info to identify its own messages
    auth_info = client.auth_test()
    if auth_info.get('team_id') != team_id:
        return 'Slack token and configured workspace do not match.'
    bot_user_id = auth_info['user_id']

    incoming = event_data.get('text', '').strip()
    mention_str = f"<@{bot_user_id}>"
    if incoming.startswith(mention_str):
        incoming = incoming[len(mention_str):].strip()
    document_command = re.match(r'^(?:documents\s*:|/documents\b)\s*(.*)$', incoming, re.IGNORECASE | re.DOTALL)
    if document_command:
        try:
            output = _slack_document_reply(org, event_data, document_command.group(1).strip())
        except Exception:
            import logging
            logging.getLogger(__name__).exception('Document Explorer Slack answer failed')
            output = 'Document Explorer could not complete this request. Please try again in DataGov.'
        client.chat_postMessage(channel=channel_id, thread_ts=thread_ts, text=output,
                                unfurl_links=False, unfurl_media=False,
                                metadata={'event_type': 'document_explorer_answer', 'event_payload': {}})
        return 'Document Explorer reply sent.'

    # Fetch thread history
    # Include groups:history equivalent by using the standard conversations_replies endpoint
    # which works for public/private channels and DMs automatically as long as the scopes are present
    history_response = client.conversations_replies(
        channel=channel_id,
        ts=thread_ts,
        include_all_metadata=True,
    )

    messages = history_response.get('messages', [])
    formatted_history = []

    for msg in messages:
        # Use the triggering event, not the most recent fetched message: newer
        # messages can arrive while this queued task is waiting for a worker.
        if msg.get('ts', '') >= event_data.get('ts', ''):
            continue
        if (msg.get('metadata') or {}).get('event_type') == 'document_explorer_answer':
            continue
        text = msg.get('text', '')
        if not text:
            continue

        # If the message was from the bot
        if msg.get('user') == bot_user_id or msg.get('bot_id'):
            formatted_history.append(ModelResponse(parts=[TextPart(content=text)]))
        else:
            formatted_history.append(ModelRequest(parts=[UserPromptPart(content=text)]))

    new_message = incoming

    # Strip mention from new message if needed
    mention_str = f"<@{bot_user_id}>"
    if new_message.startswith(mention_str):
        new_message = new_message.replace(mention_str, '', 1).strip()

    debug_log: list = []

    # Same context-first agent as the web chat: front-loaded catalog +
    # per-integration schema/run tools (PowerBI live values via
    # get_pb_measure_schema → powerbi_run_dax_query). The Slack
    # thread is the memory — prior turns arrive via ``formatted_history``.
    agent = build_chatbot_agent_for_org(
        org,
        record_call=debug_log.append,
        surface='slack',
        chat_session=None,
    )

    # Same guardrails as the web chat (``run_chat_event_sync``). Without them a
    # single stalled model round-trip or tool HTTP call pinned this turn for up
    # to Q_CLUSTER['timeout'] (1h): the broker row sat "Running" in the Queues
    # panel, the Slack thread got nothing, and because a timeout-killed worker
    # never acknowledges its row, the same message was silently re-dequeued and
    # re-run once the lock expired. A wall-clock timeout plus a per-run
    # UsageLimits cap means the thread always gets an answer instead.
    from pydantic_ai import capture_run_messages
    from pydantic_ai.exceptions import UsageLimitExceeded

    from .views import (
        AGENT_TIMEOUT_SECONDS,
        _agent_usage_limits,
        _finalize_partial_answer,
        _get_chatbot_model_for_org,
        _run_with_timeout,
        retry_transient_llm_errors,
    )

    chatbot_model_id = _get_chatbot_model_for_org(org)
    budget_hit = {'value': False, 'text': ''}
    # Shared out of the worker thread so a wall-clock timeout (which abandons
    # that thread mid-run) can still synthesise a partial answer.
    captured = {'messages': None}

    def _run_agent():
        with capture_run_messages() as run_messages:
            captured['messages'] = run_messages
            try:
                return retry_transient_llm_errors(
                    lambda: agent.run_sync(
                        user_prompt=new_message,
                        message_history=formatted_history,
                        usage_limits=_agent_usage_limits(),
                    )
                )
            except UsageLimitExceeded:
                budget_hit['value'] = True
                budget_hit['text'] = _finalize_partial_answer(
                    chatbot_model_id, run_messages,
                )
                return None

    timeout_seconds = getattr(org, 'chat_timeout_seconds', None) or AGENT_TIMEOUT_SECONDS
    try:
        result = _run_with_timeout(_run_agent, timeout_seconds)
    except TimeoutError:
        snapshot = list(captured['messages'] or [])
        print(
            f'Slack agent run hit the {timeout_seconds}s wall-clock timeout; '
            f'finalising a partial answer from {len(snapshot)} captured messages.',
            file=sys.stderr,
        )
        budget_hit['value'] = True
        budget_hit['text'] = _finalize_partial_answer(chatbot_model_id, snapshot)
        result = None

    if budget_hit['value']:
        output_text = budget_hit['text'] or (
            "I gathered a lot but couldn't fully finish this question within "
            "its time and tool budget. Please narrow it — e.g. name a specific "
            "report, measure, or workspace — and I'll answer precisely."
        )
    else:
        output_text = result.output

    if org and org.debug_responses_enabled:
        from .services.debug_render import build_debug_payload, render_debug_section
        output_text = (output_text or '') + render_debug_section(build_debug_payload(debug_log))

    # Pre-process: Slack only allows 1 table per message in Block Kit.
    # We split the message so each table goes into its own message,
    # but keep trailing text attached to the final table.
    table_pattern = r'((?:^\|.*?\|\s*?(?:\n|$))+)'
    parts = re.split(table_pattern, output_text, flags=re.MULTILINE)

    total_tables = 0
    for i, part in enumerate(parts):
        if i % 2 == 1 and re.search(r'\|[\-\s:]+\|', part):
            total_tables += 1

    messages_to_send = []
    current_message = ""
    tables_seen = 0

    for i, part in enumerate(parts):
        is_match = (i % 2 == 1)
        is_real_table = False

        if is_match:
            if re.search(r'\|[\-\s:]+\|', part):
                is_real_table = True

        current_message += part

        if is_real_table:
            tables_seen += 1
            if tables_seen < total_tables:
                if current_message.strip():
                    messages_to_send.append(current_message.strip())
                current_message = ""

    if current_message.strip():
        messages_to_send.append(current_message.strip())

    # Reply with each chunk
    for msg_text in messages_to_send:
        # Use slack-blocks-markdown to convert Markdown response directly into interactive Block Kit blocks
        blocks = markdown_to_blocks(msg_text)

        client.chat_postMessage(
            channel=channel_id,
            thread_ts=thread_ts,
            text="Assistant replied:", # Fallback text
            blocks=blocks
        )

    # Returned to Django-Q as Task.result so the reply is visible in the
    # Queues panel. Fall back to a marker when the agent produced no text.
    return output_text or "(no reply text)"

@csrf_exempt
def slack_events(request):
    if request.method != 'POST':
        return HttpResponse(status=405)
    if not _slack_request_valid(request):
        return HttpResponse(status=403)
        
    try:
        data = json.loads(request.body)
    except Exception:
        return HttpResponse(status=400)
    if not isinstance(data, dict):
        return HttpResponse(status=400)
        
    if data.get('type') == 'url_verification':
        return JsonResponse({'challenge': data.get('challenge')})
        
    if data.get('type') == 'event_callback':
        event = data.get('event', {})
        if not isinstance(event, dict):
            return HttpResponse(status=400)
        event_type = event.get('type')
        
        if event_type in ['app_mention', 'message']:
            # Ignore bot's own messages
            if event.get('bot_id') or event.get('subtype'):
                return HttpResponse(status=200)
            if event_type == 'message' and event.get('channel_type') != 'im':
                return HttpResponse(status=200)

            team_id = data.get('team_id')
            if not isinstance(team_id, str) or not team_id:
                return HttpResponse(status=400)
            org = Organization.objects.filter(slack_team_id=team_id).exclude(slack_bot_token__isnull=True).exclude(slack_bot_token='').first()
            
            if org and org.slack_bot_token:
                event_id = data.get('event_id')
                if not isinstance(event_id, str) or not event_id:
                    return HttpResponse(status=400)
                dedupe_key = 'slack_event_' + hashlib.sha256(f'{team_id}:{event_id}'.encode()).hexdigest()
                if not cache.add(dedupe_key, True, timeout=86400):
                    return HttpResponse(status=200)
                event['_slack_team_id'] = team_id
                # Process async to avoid 3s timeout. Using Django Q2 worker queue.
                try:
                    async_task('catalog.slack_views.run_slack_event_sync', event, org.slack_bot_token)
                except Exception:
                    cache.delete(dedupe_key)
                    return HttpResponse(status=503)
                
    return HttpResponse(status=200)


@api_login_required
def slack_oauth(request):
    """
    Handles the OAuth callback for the Slack Bot (app_mentions:read + chat:write).
    """
    return _handle_slack_oauth(request, hook_type='slack', redirect_name='integrations')


@api_login_required
def slack_alerts_oauth(request):
    """
    Handles the OAuth callback for Slack Alerts (chat:write only).
    """
    return _handle_slack_oauth(request, hook_type='slack_alerts', redirect_name='integrations')


def _handle_slack_oauth(request, hook_type, redirect_name):
    code = request.GET.get('code')
    error = request.GET.get('error')

    if error:
        return HttpResponse(f"Error during Slack authentication: {error}")

    if not code:
        return HttpResponse("No code provided by Slack.")

    client = WebClient()

    try:
        redirect_uri = f"https://{request.get_host()}/api/slack/oauth/" if hook_type == 'slack' else f"https://{request.get_host()}/api/slack/alerts-oauth/"
        response = client.oauth_v2_access(
            client_id=settings.SLACK_CLIENT_ID,
            client_secret=settings.SLACK_CLIENT_SECRET,
            code=code,
            redirect_uri=redirect_uri
        )

        bot_token = response.get("access_token")

        memberships = list(OrganizationMembership.objects.filter(user=request.user, is_admin=True).select_related('organization')[:2])
        if len(memberships) == 1:
            org = memberships[0].organization
            team_id = (response.get('team') or {}).get('id')
            if not bot_token or not team_id:
                return HttpResponse('Slack did not return a workspace installation.', status=400)
            if hook_type == 'slack' and Organization.objects.filter(slack_team_id=team_id).exclude(pk=org.pk).exists():
                return HttpResponse('This Slack workspace is already connected to another organization.', status=409)

            from .models import IntegrationHook
            hook, _ = IntegrationHook.objects.get_or_create(
                organization=org,
                hook_type=hook_type,
                defaults={'name': 'Slack Bot' if hook_type == 'slack' else 'Slack Alerts'}
            )
            hook.slack_bot_token = bot_token
            hook.is_active = True
            hook.save()

            # Keep Organization.slack_bot_token in sync for bot hook (used by event handler)
            if hook_type == 'slack':
                org.slack_bot_token = bot_token
                org.slack_team_id = team_id
                org.save(update_fields=['slack_bot_token', 'slack_team_id'])

            return HttpResponse(
                "Slack connected successfully. You can close this window and "
                "return to the Integrations page."
            )
        else:
            return HttpResponse('A single organization administrator membership is required.', status=403)

    except Exception as e:
        import traceback
        traceback.print_exc()
        return HttpResponse(f"Failed to authenticate with Slack: {str(e)}")
